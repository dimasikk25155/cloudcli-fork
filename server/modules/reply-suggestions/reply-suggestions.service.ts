import { createHash } from 'node:crypto';

import { replyFingerprint } from '../../../shared/reply-fingerprint.js';
import { lastReplyTurn, type ReplyTurnMessage } from '../../../shared/reply-turn.js';
import { sessionsDb } from '@/modules/database/index.js';
import { canUserAccessSession } from '@/shared/project-access.js';
import { completeJson, localLlmModel, type CompleteJsonOptions } from '@/shared/local-llm.js';
import { classifyTurnEnding, finalParagraph } from '@/shared/turn-ending.js';
import {
  buildPrompt,
  filterSuggestions,
  SYSTEM_PROMPT,
  type ReplyPromptTurn,
} from '@/modules/reply-suggestions/reply-suggestions.prompt.js';

export {
  MAX_SUGGESTION_CHARS,
  MAX_SUGGESTIONS,
  MIN_SUGGESTIONS,
} from '@/modules/reply-suggestions/reply-suggestions.prompt.js';

/**
 * Reply chips: 2–3 short answers Dima can tap after a turn that ended with a
 * question or a request. Generated by the local model, cached per session and
 * per assistant reply, so reopening a chat never re-runs the model.
 *
 * Works for every engine: the input is the normalized transcript.
 */

const MODEL_TIMEOUT_MS = 8000;
const MODEL_MAX_TOKENS = 200;
const MODEL_TEMPERATURE = 0.3;
const HISTORY_WINDOW = 40;
const CACHE_LIMIT = 300;

type HistoryMessage = ReplyTurnMessage;

export type ReplySuggestionsUser = { id: number | string; role?: string | null };

export type ReplySuggestionsDependencies = {
  fetchHistory?: (sessionId: string) => Promise<{ messages: HistoryMessage[] }>;
  complete?: (options: CompleteJsonOptions) => Promise<unknown | null>;
};

export type ReplySuggestionsResult =
  | { status: 'ok'; suggestions: string[] }
  /** The transcript shows a different reply than the client (not caught up yet). */
  | { status: 'stale' }
  | { status: 'not_found' }
  | { status: 'forbidden' };

async function defaultFetchHistory(sessionId: string): Promise<{ messages: HistoryMessage[] }> {
  const { sessionsService } = await import('@/modules/providers/services/sessions.service.js');
  return sessionsService.fetchHistory(sessionId, { limit: HISTORY_WINDOW, offset: 0 });
}

export function createReplySuggestionsService(dependencies: ReplySuggestionsDependencies = {}) {
  const fetchHistory = dependencies.fetchHistory ?? defaultFetchHistory;
  const complete = dependencies.complete ?? completeJson;
  // key = sessionId + hash of the assistant reply; a Map keeps insertion order for eviction.
  const cache = new Map<string, string[]>();
  const inFlight = new Map<string, Promise<string[] | null>>();

  function remember(key: string, suggestions: string[]): void {
    cache.delete(key);
    cache.set(key, suggestions);
    while (cache.size > CACHE_LIMIT) {
      const oldest = cache.keys().next().value;
      if (oldest === undefined) break;
      cache.delete(oldest);
    }
  }

  async function generate(key: string, turn: ReplyPromptTurn): Promise<string[] | null> {
    const raw = await complete({
      system: SYSTEM_PROMPT,
      prompt: buildPrompt(turn),
      model: localLlmModel('suggest'),
      timeoutMs: MODEL_TIMEOUT_MS,
      maxTokens: MODEL_MAX_TOKENS,
      temperature: MODEL_TEMPERATURE,
    });
    if (raw === null) {
      // Model down or confused: show nothing now, try again next time.
      return null;
    }
    const suggestions = filterSuggestions(raw, turn.question);
    remember(key, suggestions);
    return suggestions;
  }

  /**
   * `replyHash` is the fingerprint of the reply the client is showing. Chips
   * are only generated for that exact reply: if the server's transcript has
   * not caught up yet (or has moved on), the answer is empty and nothing is cached.
   */
  async function suggest(
    user: ReplySuggestionsUser,
    sessionId: string,
    replyHash: string,
  ): Promise<ReplySuggestionsResult> {
    const session = sessionsDb.getSessionById(sessionId);
    if (!session) {
      return { status: 'not_found' };
    }
    if (!canUserAccessSession(user, sessionId)) {
      return { status: 'forbidden' };
    }

    let messages: HistoryMessage[];
    try {
      ({ messages } = await fetchHistory(sessionId));
    } catch {
      return { status: 'ok', suggestions: [] };
    }
    const turn = lastReplyTurn(messages);
    if (!turn || replyFingerprint(turn.assistant) !== replyHash) {
      return { status: 'stale' };
    }
    if (classifyTurnEnding(turn.assistant).kind === 'none') {
      return { status: 'ok', suggestions: [] };
    }

    const key = `${sessionId}:${createHash('sha256').update(turn.assistant).digest('hex')}`;
    const cached = cache.get(key);
    if (cached) {
      return { status: 'ok', suggestions: cached };
    }
    let pending = inFlight.get(key);
    if (!pending) {
      pending = generate(key, { ...turn, question: finalParagraph(turn.assistant) }).finally(() => inFlight.delete(key));
      inFlight.set(key, pending);
    }
    return { status: 'ok', suggestions: (await pending) ?? [] };
  }

  return { suggest };
}

export type ReplySuggestionsService = ReturnType<typeof createReplySuggestionsService>;

export const replySuggestions = createReplySuggestionsService();

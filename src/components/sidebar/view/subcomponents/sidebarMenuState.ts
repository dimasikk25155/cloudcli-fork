/**
 * Когда складка «Меню» внизу сайдбара сворачивается сама.
 *
 * На компьютере сайдбар монтируется один раз — складка свёрнута при монтировании,
 * сигнала шторки нет (`undefined`). На телефоне шторка не размонтируется, а
 * прячется (`invisible`/`-translate-x-full`), поэтому без сигнала раскрытая
 * сетка пережила бы закрытие и встретила следующее открытие раскрытой.
 *
 * @param previous открыта ли шторка была на прошлом рендере (`undefined` — шторки нет)
 * @param current открыта ли шторка сейчас
 * @returns `true` — свернуть: шторка только что открылась
 */
export function shouldCollapseMenu(previous?: boolean, current?: boolean): boolean {
  return current === true && previous === false;
}
